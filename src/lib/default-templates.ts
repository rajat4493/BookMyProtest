export const DEFAULT_TEMPLATES: DocTemplate[] = Object.entries(T).map(([key, [name, content]]) => ({
  id: `builtin:${key}`, templateKey: key, name, jurisdictionId: null, authorityId: null, version: 0, content, disclaimer: D,
  active: true, effectiveFrom: null, effectiveUntil: null, sourceId: null,
}));

type Q = (text: string, params?: unknown[]) => Promise<{ rowCount: number | null }>;

/** Idempotent: inserts v1 of each global default template if the key has no global template yet. */
export async function ensureDefaultTemplates(q: Q) {
  for (const t of DEFAULT_TEMPLATES) {
    await q(
      `INSERT INTO document_templates (template_key, name, jurisdiction_id, version, content, disclaimer)
       SELECT $1,$2,NULL,1,$3,$4 WHERE NOT EXISTS (SELECT 1 FROM document_templates WHERE template_key=$1 AND jurisdiction_id IS NULL)`,
      [t.templateKey, t.name, t.content, t.disclaimer],
    );
  }
}
