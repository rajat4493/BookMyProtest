import type { Answers, EvaluatedItem } from "./engine/types";
import { isActionable } from "./engine/evaluate";
import type { Readiness } from "./engine/readiness";
import { renderTemplate, type DocTemplate, type Vars } from "./engine/templates";
import { DEFAULT_TEMPLATES } from "./default-templates";

export const DISCLAIMER = "Draft generated by BookMyProtest. Verify requirements with the relevant authority before submission.";

export const DOC_KINDS = [
  { slug: "event-summary", title: "Event summary", blurb: "One page: what, where, when, how many." },
  { slug: "organizer-details", title: "Organizer details sheet", blurb: "Who is responsible and how to reach them." },
  { slug: "route-details", title: "Route details sheet", blurb: "Start, destination and timings." },
  { slug: "document-checklist", title: "Document checklist", blurb: "What to prepare, and what is still missing." },
  { slug: "request-letter", title: "Draft request letter", blurb: "A starting point to adapt and sign yourself." },
  { slug: "undertaking", title: "Undertaking template", blurb: "A plain template. Check the authority's own format." },
] as const;
export type DocKind = (typeof DOC_KINDS)[number]["slug"];

export interface DocContext {
  answers: Answers;
  cityLabel: string;
  items: EvaluatedItem[];
  readiness: Readiness;
  generatedOn: string; // YYYY-MM-DD
  /** Templates already selected for this place and date (see selectTemplate). Missing keys fall back to built-in defaults. */
  templates?: Partial<Record<string, DocTemplate>>;
}

export interface DocBlock { heading?: string; rows?: [string, string][]; paragraphs?: string[]; bullets?: string[] }
export interface BuiltDoc { slug: DocKind; title: string; blocks: DocBlock[]; disclaimer: string; templateId: string | null; templateVersion: number }

const yn = (b: boolean) => (b ? "Yes" : "No");
const ORG_LABEL: Record<Answers["organizerType"], string> = { individual: "Individual", group: "Group / collective", student: "Student body", ngo: "Non-profit / NGO", union: "Union / association", other: "Other" };

export function templateVars(ctx: DocContext, authorityName = ""): Vars {
  const a = ctx.answers;
  const kind = a.kind === "march" ? "March" : "Static gathering";
  return {
    organizer_name: a.organizerName, organizer_type_label: ORG_LABEL[a.organizerType], organizer_type_lower: ORG_LABEL[a.organizerType].toLowerCase(),
    organizer_email: a.organizerEmail, contact_number: a.organizerPhone,
    event_name: a.name, event_date: a.date, start_time: a.startTime, end_time: a.endTime, expected_attendance: String(a.attendance),
    start_location: a.startLocation, destination: a.kind === "march" ? a.destination : "", route: a.kind === "march" ? `${a.startLocation} → ${a.destination}` : a.startLocation,
    purpose: a.description.trim(), city_label: ctx.cityLabel, generated_on: ctx.generatedOn, authority_name: authorityName,
    kind_label: kind, kind_lower: kind.toLowerCase(), march: a.kind === "march" ? "true" : "",
    stage_yn: yn(a.stage), sound_yn: yn(a.sound), vehicles_yn: yn(a.vehicles), food_yn: yn(a.food),
    stage_yn_lower: yn(a.stage).toLowerCase(), sound_yn_lower: yn(a.sound).toLowerCase(), vehicles_yn_lower: yn(a.vehicles).toLowerCase(), food_yn_lower: yn(a.food).toLowerCase(),
    readiness_pct: String(ctx.readiness.pct),
  };
}

function checklistBlocks(ctx: DocContext): DocBlock[] {
  const open = ctx.items.filter(isActionable);
  return (["permissions", "documents", "logistics", "safety"] as const)
    .map((cat) => ({
      heading: cat[0].toUpperCase() + cat.slice(1),
      bullets: open.filter((i) => i.rule.category === cat).map(
        (i) => `[${i.done ? "x" : " "}] ${i.rule.title} (${i.level.replace("_", " ").toLowerCase()})${i.evidence === "needs_verification" ? " — needs verification" : ""}`,
      ),
    }))
    .filter((b) => b.bullets.length > 0);
}

export function buildDocument(slug: DocKind, ctx: DocContext): BuiltDoc {
  const t = ctx.templates?.[slug] ?? DEFAULT_TEMPLATES.find((d) => d.templateKey === slug)!;
  const blocks = renderTemplate(t.content, templateVars(ctx, t.authorityName ?? ""), { checklist: checklistBlocks(ctx) });
  return { slug, title: t.name, blocks, disclaimer: t.disclaimer, templateId: t.id.startsWith("builtin:") ? null : t.id, templateVersion: t.version };
}

export function buildAll(ctx: DocContext): BuiltDoc[] {
  return DOC_KINDS.map((d) => buildDocument(d.slug, ctx));
}

export function docToText(d: BuiltDoc): string {
  const out: string[] = [d.title.toUpperCase(), ""];
  for (const b of d.blocks) {
    if (b.heading) out.push(b.heading.toUpperCase());
    b.rows?.forEach(([k, v]) => out.push(`${k}: ${v}`));
    b.paragraphs?.forEach((p) => out.push(p, ""));
    b.bullets?.forEach((x) => out.push(x.startsWith("[") ? x : `- ${x}`));
    out.push("");
  }
  out.push("---", d.disclaimer);
  return out.join("\n");
}
