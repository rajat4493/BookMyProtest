import type { Answers, EvaluatedItem } from "./engine/types";
import { isActionable } from "./engine/evaluate";
import type { Readiness } from "./engine/readiness";

export const DISCLAIMER = "Draft generated by BookMyProtest. Verify requirements with the relevant authority before submission.";

export const DOC_KINDS = [
  { slug: "event-summary", title: "Event summary", blurb: "One page: what, where, when, how many." },
  { slug: "organizer-details", title: "Organizer details sheet", blurb: "Who is responsible and how to reach them." },
  { slug: "route-details", title: "Route details sheet", blurb: "Start, destination and timings." },
  { slug: "document-checklist", title: "Document checklist", blurb: "What to prepare, and what is still missing." },
  { slug: "request-letter", title: "Draft request letter", blurb: "A starting point to adapt and sign yourself." },
  { slug: "undertaking", title: "Undertaking template", blurb: "A plain template. Check the authority's own format." },
] as const;
export type DocKind = (typeof DOC_KINDS)[number]["slug"];

export interface DocContext {
  answers: Answers;
  cityLabel: string;
  items: EvaluatedItem[];
  readiness: Readiness;
  generatedOn: string; // YYYY-MM-DD
}

export interface DocBlock { heading?: string; rows?: [string, string][]; paragraphs?: string[]; bullets?: string[] }
export interface BuiltDoc { slug: DocKind; title: string; blocks: DocBlock[]; disclaimer: string }

const yn = (b: boolean) => (b ? "Yes" : "No");
const orBlank = (s: string) => (s.trim() ? s : "______________________");
const kindLabel = (a: Answers) => (a.kind === "march" ? "March" : "Static gathering");
const ORG_LABEL: Record<Answers["organizerType"], string> = { individual: "Individual", group: "Group / collective", student: "Student body", ngo: "Non-profit / NGO", union: "Union / association", other: "Other" };

export function buildDocument(slug: DocKind, ctx: DocContext): BuiltDoc {
  const { answers: a, cityLabel } = ctx;
  const title = DOC_KINDS.find((d) => d.slug === slug)!.title;
  const when = `${a.date}, ${a.startTime}–${a.endTime}`;
  let blocks: DocBlock[];

  switch (slug) {
    case "event-summary":
      blocks = [
        { rows: [["Event", a.name], ["City", cityLabel], ["Date and time", when], ["Type", kindLabel(a)], ["Expected attendance", String(a.attendance)], ["Starting location", a.startLocation],
          ...(a.kind === "march" ? ([["Destination", a.destination]] as [string, string][]) : []),
          ["Stage", yn(a.stage)], ["Loudspeaker / sound", yn(a.sound)], ["Vehicles involved", yn(a.vehicles)], ["Food or water distribution", yn(a.food)]] },
        { heading: "Purpose", paragraphs: [a.description.trim() || "Not provided yet. Add a short description of the purpose and format."] },
      ];
      break;
    case "organizer-details":
      blocks = [
        { rows: [["Organizer name", a.organizerName], ["Organizer type", ORG_LABEL[a.organizerType]], ["Email", a.organizerEmail], ["Phone", orBlank(a.organizerPhone)], ["Event", a.name], ["Event date", a.date]] },
        { heading: "Additional responsible persons", paragraphs: ["Name: ______________________   Phone: ______________________", "Name: ______________________   Phone: ______________________"] },
        { heading: "ID reference", paragraphs: ["Attach a copy of the organizer's photo ID. Do not paste ID numbers into this sheet."] },
      ];
      break;
    case "route-details":
      blocks = a.kind === "march"
        ? [
            { rows: [["Event", a.name], ["Date", a.date], ["Start time", a.startTime], ["Expected end time", a.endTime], ["Starting point", a.startLocation], ["Destination", a.destination], ["Expected attendance", String(a.attendance)], ["Vehicles on route", yn(a.vehicles)]] },
            { heading: "Route description", paragraphs: ["List the roads in order, with landmarks, from start to destination:", "1. ______________________", "2. ______________________", "3. ______________________"] },
            { heading: "Timings", paragraphs: ["Assembly: ________   Departure: ________   Arrival: ________   Dispersal: ________"] },
          ]
        : [
            { rows: [["Event", a.name], ["Date", a.date], ["Time", `${a.startTime}–${a.endTime}`], ["Location", a.startLocation], ["Type", "Static gathering (no route)"]] },
            { heading: "Access", paragraphs: ["Entrances and exits: ______________________", "Nearest transport: ______________________"] },
          ];
      break;
    case "document-checklist": {
      const open = ctx.items.filter(isActionable);
      blocks = [
        { paragraphs: [`Readiness at ${ctx.generatedOn}: ${ctx.readiness.pct}%. Based on currently configured local requirements for ${cityLabel}.`] },
        ...(["permissions", "documents", "logistics", "safety"] as const).map((cat) => ({
          heading: cat[0].toUpperCase() + cat.slice(1),
          bullets: open.filter((i) => i.rule.category === cat).map(
            (i) => `[${i.done ? "x" : " "}] ${i.rule.title} (${i.level.replace("_", " ").toLowerCase()})${i.evidence === "needs_verification" ? " — needs verification" : ""}`,
          ),
        })).filter((b) => b.bullets.length > 0),
      ];
      break;
    }
    case "request-letter":
      blocks = [
        { paragraphs: [
            `Date: ${ctx.generatedOn}`,
            "To,\nThe Competent Authority\n(Name and address of the relevant office: ______________________)",
            `Subject: Intimation and request for arrangements for a public gathering — ${a.name}`,
            "Sir/Madam,",
            `I, ${a.organizerName}, writing as ${ORG_LABEL[a.organizerType].toLowerCase()} organizer, wish to inform you of a ${kindLabel(a).toLowerCase()} planned in ${cityLabel} and to request any permissions or arrangements that apply.`,
            `Date and time: ${when}\nStarting location: ${a.startLocation}${a.kind === "march" ? `\nDestination: ${a.destination}` : ""}\nExpected attendance: approximately ${a.attendance}`,
            `Purpose: ${a.description.trim() || "______________________"}`,
            `Arrangements: stage — ${yn(a.stage).toLowerCase()}; loudspeaker/sound — ${yn(a.sound).toLowerCase()}; vehicles — ${yn(a.vehicles).toLowerCase()}; food or water distribution — ${yn(a.food).toLowerCase()}.`,
            "I request that you let me know of any conditions, documents or timings I should follow. I can be reached using the details below.",
            `Yours faithfully,\n\n______________________\n${a.organizerName}\n${a.organizerEmail}${a.organizerPhone ? `\n${a.organizerPhone}` : ""}`,
        ] },
      ];
      break;
    case "undertaking":
      blocks = [
        { paragraphs: [
            `I, ${a.organizerName}, the organizer of "${a.name}" planned for ${a.date} in ${cityLabel}, state that:`,
          ] },
        { bullets: [
            "The information I have provided about this gathering is accurate to the best of my knowledge.",
            "I will follow the conditions communicated by the relevant authority.",
            "I will make reasonable arrangements for the safety and orderly conduct of participants.",
            "I will keep the venue and route clean and will leave them as I found them.",
            "I will tell the authority promptly if the plan changes materially.",
        ] },
        { paragraphs: [`Place: ______________________    Date: ______________________\n\nSignature: ______________________\n${a.organizerName}`, "This is a plain template. Some authorities require their own format; check before use."] },
      ];
      break;
  }
  return { slug, title, blocks, disclaimer: DISCLAIMER };
}

export function buildAll(ctx: DocContext): BuiltDoc[] {
  return DOC_KINDS.map((d) => buildDocument(d.slug, ctx));
}

export function docToText(d: BuiltDoc): string {
  const out: string[] = [d.title.toUpperCase(), ""];
  for (const b of d.blocks) {
    if (b.heading) out.push(b.heading.toUpperCase());
    b.rows?.forEach(([k, v]) => out.push(`${k}: ${v}`));
    b.paragraphs?.forEach((p) => out.push(p, ""));
    b.bullets?.forEach((x) => out.push(x.startsWith("[") ? x : `- ${x}`));
    out.push("");
  }
  out.push("---", d.disclaimer);
  return out.join("\n");
}
