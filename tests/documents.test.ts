import { describe, expect, it } from "vitest";
import { DISCLAIMER, DOC_KINDS, buildAll, docToText } from "@/lib/documents";
import { evaluate } from "@/lib/engine/evaluate";
import { computeReadiness } from "@/lib/engine/readiness";
import { parseAnswers } from "@/lib/validation";
import { baseAnswers as a, rule } from "./fixtures";

const mk = (answers = a) => {
  const items = evaluate([rule({ id: "r1", title: "Police intimation" })], answers);
  return { answers, cityLabel: "Testville, Testland", items, readiness: computeReadiness(items), generatedOn: "2026-10-09" };
};

describe("documents", () => {
  it("builds all six templates, each with the mandatory disclaimer", () => {
    const docs = buildAll(mk());
    expect(docs).toHaveLength(DOC_KINDS.length);
    for (const d of docs) {
      expect(d.disclaimer).toBe(DISCLAIMER);
      expect(docToText(d)).toContain("Draft generated by BookMyProtest. Verify requirements with the relevant authority before submission.");
    }
  });
  it("contains event data and never a seal or pre-filled signature", () => {
    const text = buildAll(mk({ ...a, kind: "march", destination: "City Hall" })).map(docToText).join("\n");
    expect(text).toContain("Test assembly");
    expect(text).toContain("City Hall");
    expect(text.toLowerCase()).not.toContain("seal of");
    expect(text).toContain("Signature: ______________________");
  });
  it("checklist marks done and unverified items", () => {
    const text = docToText(buildAll(mk())[3]);
    expect(text).toContain("[ ] Police intimation");
    expect(text).toContain("needs verification");
  });
});

describe("answers validation", () => {
  const good = { ...a, stage: "on", sound: "true" };
  it("accepts a good submission and coerces checkbox values", () => {
    const r = parseAnswers(good);
    expect(r.ok && r.answers.stage && r.answers.sound && !r.answers.food).toBe(true);
  });
  it("march needs a destination; end must follow start", () => {
    const r = parseAnswers({ ...good, kind: "march", destination: "" });
    expect(!r.ok && r.errors.destination).toBeTruthy();
    const t = parseAnswers({ ...good, endTime: "09:00" });
    expect(!t.ok && t.errors.endTime).toBeTruthy();
  });
  it("rejects bad email and zero attendance", () => {
    const r = parseAnswers({ ...good, organizerEmail: "nope", attendance: 0 });
    expect(!r.ok && Object.keys(r.errors)).toEqual(expect.arrayContaining(["organizerEmail", "attendance"]));
  });
});
